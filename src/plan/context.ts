import type { RepoFacts } from "../types";

export { ENRICH_FILES } from "../enrich";
import { ENRICH_FILES } from "../enrich";

const ENRICH_WHEN: Record<(typeof ENRICH_FILES)[number], string> = {
  "architecture.md": "you need the big picture: modules and how they depend on each other",
  "flows.md": "you are tracing a request, job or user flow end to end",
  "gotchas.md": "something behaves unexpectedly or before touching fragile areas",
};

export function stackSummary(f: RepoFacts): string {
  const base = f.frameworks.length ? f.frameworks.slice(0, 3) : f.languages;
  const parts: string[] = [...base];
  if (f.packageManager !== "none") parts.push(f.packageManager);
  return parts.join(" · ");
}

/** Resolved check commands, in the order they should run. */
export function checkCommands(f: RepoFacts): string[] {
  const c = f.commands;
  return [c.typecheck, c.lint, c.test, c.build].filter((x): x is string => !!x);
}

export function hasDataRef(f: RepoFacts): boolean {
  return f.dataModels.length > 0 || f.envVars.length > 0;
}

const bullets = (items: string[]) => items.map((i) => `- ${i}`).join("\n");

export function contextSkill(f: RepoFacts, enriched: string[], date: string): string {
  const summary = stackSummary(f);
  const description = `Use when working in the ${f.name} repo (${summary}): before planning, implementing, reviewing or debugging anything in it. Maps the stack, commands, structure, data and conventions, and indexes deeper references.`;
  const checks = checkCommands(f);

  const glance = [
    `Stack: ${summary || "not detected"}`,
    ...(f.packageManager !== "none"
      ? [`Package manager: ${f.packageManager} (use it for every install and script)`]
      : []),
    `Default branch: \`${f.git.defaultBranch ?? "main"}\``,
    checks.length
      ? `Before claiming done: ${checks.map((c) => `\`${c}\``).join(", ")}`
      : "No check commands detected; ask which to run before claiming done",
  ];

  const places = f.structure
    .filter((d) => !d.path.includes("/"))
    .slice(0, 12)
    .map((d) => `\`${d.path}/\`${d.role ? `: ${d.role}` : ""}`);

  const refs: [string, string][] = [
    ["stack.md", "you need the frameworks, languages and key dependencies"],
    ["commands.md", "you need to run, check or build something"],
    ["structure.md", "you are looking for where code lives or which routes exist"],
  ];
  if (hasDataRef(f)) {
    refs.push(["data.md", "you touch the data model, migrations or environment variables"]);
  }
  refs.push(["conventions.md", "you commit, branch, or write code that must match house style"]);
  for (const n of ENRICH_FILES) if (enriched.includes(n)) refs.push([n, ENRICH_WHEN[n]]);

  return [
    "---",
    `name: ${f.slug}-context`,
    `description: ${JSON.stringify(description)}`,
    "---",
    "",
    `# ${f.name}: repo context`,
    "",
    f.description ?? `A ${summary} project.`,
    "",
    "## At a glance",
    "",
    bullets(glance),
    "",
    "## Where things live",
    "",
    places.length ? bullets(places) : "No top-level structure detected.",
    "",
    "## References",
    "",
    "| File | Read it when |",
    "|---|---|",
    ...refs.map(([file, when]) => `| \`references/${file}\` | ${when} |`),
    "",
    `Generated by agent-kickoff on ${date}. Re-run \`bunx agent-kickoff\` to refresh; anything outside the agent-kickoff markers is kept.`,
    "",
  ].join("\n");
}

export function stackMd(f: RepoFacts): string {
  const lines = ["# Stack", ""];
  lines.push(`- Languages: ${f.languages.join(", ") || "not detected"}`);
  lines.push(`- Frameworks: ${f.frameworks.join(", ") || "none detected"}`);
  lines.push(`- Package manager: ${f.packageManager}`);
  if (f.testRunner) lines.push(`- Test runner: ${f.testRunner}`);
  if (f.isMonorepo) {
    lines.push(`- Monorepo workspaces: ${f.workspaces.map((w) => `\`${w}\``).join(", ") || "yes"}`);
  }
  if (f.ciJobs.length) lines.push(`- CI jobs: ${f.ciJobs.join(", ")}`);
  if (f.dependencies.length) {
    lines.push("", "## Dependencies", "", f.dependencies.map((d) => `\`${d}\``).join(", "));
  }
  return lines.join("\n") + "\n";
}

export function commandsMd(f: RepoFacts): string {
  const c = f.commands;
  const rows: [string, string | undefined, string][] = [
    ["Dev", c.dev, "to run the app locally"],
    ["Typecheck", c.typecheck, "after any code change, before claiming done"],
    ["Lint", c.lint, "after any code change, before claiming done"],
    ["Test", c.test, "after any logic change, before claiming done"],
    ["Build", c.build, "before claiming done on anything that affects the build"],
    ["Format", c.format, "when formatting is requested or CI complains"],
  ];
  const lines = ["# Commands", ""];
  const present = rows.filter(([, cmd]) => !!cmd);
  if (present.length) {
    lines.push("| Task | Command | Run it |", "|---|---|---|");
    for (const [task, cmd, when] of present) lines.push(`| ${task} | \`${cmd}\` | ${when} |`);
  } else {
    lines.push("No commands detected; ask which to run.");
  }
  const scripts = Object.entries(f.scripts);
  if (scripts.length) {
    lines.push("", "## All package.json scripts", "", "| Script | Runs |", "|---|---|");
    for (const [name, cmd] of scripts) {
      lines.push(`| \`${name}\` | \`${cmd.replace(/\|/g, "\\|")}\` |`);
    }
  }
  return lines.join("\n") + "\n";
}

export function structureMd(f: RepoFacts): string {
  const lines = ["# Structure", ""];
  if (f.structure.length) {
    for (const d of f.structure) lines.push(`- \`${d.path}/\`${d.role ? `: ${d.role}` : ""}`);
  } else {
    lines.push("No top-level structure detected.");
  }
  if (f.routes.length) {
    lines.push("", "## Routes", "", ...f.routes.map((r) => `- \`${r}\``));
  }
  return lines.join("\n") + "\n";
}

export function dataMd(f: RepoFacts): string {
  const lines = ["# Data", ""];
  if (f.dataSource) lines.push(`- Source: ${f.dataSource}`);
  if (f.dataModels.length) {
    lines.push("", "## Models", "", ...f.dataModels.map((m) => `- \`${m}\``));
  }
  if (f.dataSource === "prisma") lines.push("", "Migrations live in `prisma/migrations/`.");
  else if (f.dataSource === "drizzle") {
    lines.push("", "Migrations live in the drizzle output directory (see the drizzle config).");
  } else if (f.dataSource === "supabase") lines.push("", "Migrations live in `supabase/migrations/`.");
  if (f.envVars.length) {
    lines.push(
      "",
      "## Environment variables",
      "",
      ...f.envVars.map((v) => `- \`${v}\``),
      "",
      "Values live in the developer's untracked `.env` and are never committed.",
    );
  }
  return lines.join("\n") + "\n";
}

export function conventionsMd(f: RepoFacts): string {
  const lines = ["# Conventions", ""];
  lines.push(
    f.git.conventionalCommits
      ? "- Commits: conventional commits (`feat:`, `fix:`, `chore:`…)."
      : "- Commits: no conventional-commit pattern detected; follow the style of recent history.",
  );
  lines.push(`- Default branch: \`${f.git.defaultBranch ?? "main"}\`.`);
  const ds = f.designSystem;
  if (ds) {
    lines.push("", "## Design system", "");
    if (ds.package) lines.push(`- Package: \`${ds.package}\``);
    if (ds.tokens) lines.push(`- Tokens: \`${ds.tokens}\` (change tokens there, not inline)`);
    if (ds.primitives) lines.push(`- Primitives: \`${ds.primitives}\` (reuse before hand-rolling)`);
  }
  if (f.docs.length) {
    lines.push(
      "",
      "## Existing instruction files",
      "",
      "These are binding; read them before working:",
      "",
      ...f.docs.map((d) => `- \`${d}\``),
    );
  }
  return lines.join("\n") + "\n";
}
